/** Look up templates by trigger and personality stage */
export function getTemplatesForTrigger(
  trigger: DialogueTemplate['trigger'],
  stage: DialogueTemplate['personalityStage'][number],
): DialogueTemplate[] {
  return DIALOGUE_TEMPLATES.filter(
    (t) => t.trigger === trigger && t.personalityStage.includes(stage),
  );
}

/** Get total template count (for validation) */
export function getTemplateCount(): number {
  return DIALOGUE_TEMPLATES.length;
}
