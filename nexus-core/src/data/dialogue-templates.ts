// 200+ real dialogue templates for the companion system
// Organized by trigger type × personality stage
// CRITICAL: No quiz language. No judgment. No gendered language.
// NEVER: "Good job!" "Correct!" "Wrong!" "Try again!" "You should know this"
// ALWAYS: "We did it!" "That's interesting!" "Hmm, what happened?" "Let's try something!"

import type { DialogueTemplate } from '../types/dialogue.js';

// Helper to build templates concisely
function t(
  id: string,
  trigger: DialogueTemplate['trigger'],
  stages: DialogueTemplate['personalityStage'],
  emotion: DialogueTemplate['emotion'],
  variants: string[],
  spoken?: string,
  screenReader?: string,
): DialogueTemplate {
  return {
    id,
    trigger,
    personalityStage: stages,
    emotion,
    variants: variants.map((text) => ({ text })),
    accessibility: {
      spokenText: spoken ?? variants[0]!,
      screenReaderText: screenReader ?? `Companion says: ${variants[0]!}`,
    },
  };
}

