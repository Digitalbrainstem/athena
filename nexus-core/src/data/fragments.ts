// ─── Combine all fragments ───────────────────────────────────────────────────

export const ALL_FRAGMENTS: readonly Fragment[] = [
  ...STAR_TRAIL,
  ...JOURNAL,
  ...MACHINES,
  ...EQUATIONS,
  ...TRUTH,
];

/** Get a fragment by ID */
export function getFragment(id: string): Fragment | undefined {
  return ALL_FRAGMENTS.find(f => f.id === id);
}

/** Get all fragments for a specific story thread */
export function fragmentsForThread(thread: StoryThread): readonly Fragment[] {
  return ALL_FRAGMENTS.filter(f => f.storyThread === thread);
}

/** Get all fragments for a specific biome */
export function fragmentsForBiome(biome: string): readonly Fragment[] {
  return ALL_FRAGMENTS.filter(f => f.biome === biome);
}

/** Get all fragments for a specific mastery tier */
export function fragmentsForTier(tier: MasteryTier): readonly Fragment[] {
  return ALL_FRAGMENTS.filter(f => f.tier === tier);
}

/** Get fragment counts by thread */
export function getThreadCounts(): Record<StoryThread, number> {
  const counts: Record<string, number> = {
    star_trail: 0, journal: 0, machines: 0, equations: 0, truth: 0,
  };
  for (const f of ALL_FRAGMENTS) {
    counts[f.storyThread] = (counts[f.storyThread] ?? 0) + 1;
  }
  return counts as Record<StoryThread, number>;
}
