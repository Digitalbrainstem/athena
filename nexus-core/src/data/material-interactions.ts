export function getInteraction(id: string): MaterialInteraction | undefined {
  return MATERIAL_INTERACTIONS.find(i => i.id === id);
}

export function findInteraction(
  materialA: string,
  materialB: string,
): MaterialInteraction | undefined {
  return MATERIAL_INTERACTIONS.find(
    i =>
      (i.materials[0] === materialA && i.materials[1] === materialB) ||
      (i.materials[0] === materialB && i.materials[1] === materialA),
  );
}

export function interactionsForTier(
  tier: import('../types/components.js').MasteryTier,
): MaterialInteraction[] {
  const tierOrder: Record<string, number> = {
    foundation: 0,
    discovery: 1,
    builder: 2,
    innovator: 3,
    creator: 4,
  };
  const maxLevel = tierOrder[tier] ?? 0;
  return MATERIAL_INTERACTIONS.filter(
    i => (tierOrder[i.minTier] ?? 0) <= maxLevel,
  );
}

export function interactionsWithMaterial(material: string): MaterialInteraction[] {
  return MATERIAL_INTERACTIONS.filter(
    i => i.materials[0] === material || i.materials[1] === material,
  );
}
