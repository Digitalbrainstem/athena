def QB(slug, title, skills, desc, steps_brief, mins=10):
    """Quick-Build quest from ultra-compact steps: [(obj, inst, succ)]"""
    steps = []
    for i, sd in enumerate(steps_brief):
        obj, inst, succ = sd[0], sd[1], sd[2]
        hints = HINT_TEMPLATES.get(obj, ['Think about each part carefully.', 'Try a different approach.'])
